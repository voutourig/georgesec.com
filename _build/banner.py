# Generates layouts/partials/banner.html (msfconsole style ASCII banner, figlet font ANSI Shadow, used as the header logo)
# and layouts/partials/info.html (the =[ georgesec v2026 ] info block at the top of the home page terminal).
# Run with /workspace/.venv/bin/python (needs pyfiglet).
import html, pathlib, pyfiglet
root = pathlib.Path(__file__).resolve().parent.parent
FONT = 'ansi_shadow'
art = pyfiglet.figlet_format('georgesec', font=FONT, width=200).rstrip('\n').split('\n')
art = [l.rstrip() for l in art if l.strip()]
info = [
    ('       =[ ', 'georgesec v2026'),
    ('+ -- --=[ ', 'detection engineering | penetration testing'),
    ('+ -- --=[ ', 'incident response | threat hunting | red team'),
    ('+ -- --=[ ', 'ECSC 2026 Cyprus national team | PJPT | BTL1'),
    ('+ -- --=[ ', 'MSc Cybersecurity at Georgia Tech'),
]
inner = max(len(t) for _, t in info) + 4
rows = []
for pre, txt in info:
    pad = ' ' * (inner - len(txt))
    rows.append(f'<span class="il"><span class="ip">{html.escape(pre)}</span><span class="it">{html.escape(txt)}</span><span class="pad">{pad}</span><span class="ip">]</span></span>')
cols = max(len(l) for l in art)
banner = (f'{{{{/* generated by _build/banner.py, font {FONT} */}}}}\n'
          f'<pre class="banner" role="img" aria-label="georgesec" style="--cols:{cols}">' + html.escape('\n'.join(art)) + '</pre>\n')
info_html = ('{{/* generated by _build/banner.py */}}\n'
       '<pre class="info" aria-label="georgesec v2026. Detection engineering and penetration testing. Incident response, threat hunting and red team. ECSC 2026 Cyprus national team, PJPT and BTL1. MSc Cybersecurity at Georgia Tech.">' + ''.join(rows) + '</pre>\n')
(root / 'layouts/partials/banner.html').write_text(banner)
(root / 'layouts/partials/info.html').write_text(info_html)
print('cols', cols, 'info width', 10 + inner + 1)
print('\n'.join(art))
